/**
 * A 32 KB original ROM used in tests. It is not a commercial title: NOP/JP to an infinite loop.
 */

const NINTENDO_LOGO = Uint8Array.from([
  0xce, 0xed, 0x66, 0x66, 0xcc, 0x0d, 0x00, 0x0b, 0x03, 0x73, 0x00, 0x83, 0x00, 0x0c, 0x00, 0x0d,
  0x00, 0x08, 0x11, 0x1f, 0x88, 0x89, 0x00, 0x0e, 0xdc, 0xcc, 0x6e, 0xe6, 0xdd, 0xdd, 0xd9, 0x99,
  0xbb, 0xbb, 0x67, 0x63, 0x6e, 0x0e, 0xec, 0xcc, 0xdd, 0xdc, 0x99, 0x9f, 0xbb, 0xb9, 0x33, 0x3e,
]);

export function buildMinimalGbRom(title = 'VAULTARA'): Uint8Array {
  const rom = new Uint8Array(0x8000);
  rom[0x100] = 0x00;
  rom[0x101] = 0xc3;
  rom[0x102] = 0x50;
  rom[0x103] = 0x01;
  rom.set(NINTENDO_LOGO, 0x104);

  const label = title.toUpperCase().slice(0, 15).padEnd(15, ' ');

  for (let index = 0; index < label.length; index += 1) {
    rom[0x134 + index] = label.charCodeAt(index);
  }

  rom[0x143] = 0x00;
  rom[0x147] = 0x00;
  rom[0x148] = 0x00;
  rom[0x149] = 0x00;
  rom[0x14a] = 0x00;
  rom[0x14b] = 0x00;
  rom[0x14c] = 0x00;

  let header = 0;

  for (let address = 0x134; address <= 0x14c; address += 1) {
    header = (header - (rom[address] ?? 0) - 1) & 0xff;
  }

  rom[0x14d] = header;
  rom[0x150] = 0x18;
  rom[0x151] = 0xfe;

  let checksum = 0;

  for (let index = 0; index < rom.byteLength; index += 1) {
    if (index === 0x14e || index === 0x14f) {
      continue;
    }

    checksum = (checksum + (rom[index] ?? 0)) & 0xffff;
  }

  rom[0x14e] = (checksum >> 8) & 0xff;
  rom[0x14f] = checksum & 0xff;

  return rom;
}
